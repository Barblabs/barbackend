// Package tenancy is the domain of Customers and their Users (ADR 0013).
package tenancy

import (
	"errors"
	"fmt"
	"strings"

	"github.com/google/uuid"
)

var (
	ErrInvalidCustomer = errors.New("invalid customer")
	ErrInvalidUser     = errors.New("invalid user")
	// ErrNoCustomer is a Platform Admin, who acts for no Customer.
	ErrNoCustomer = errors.New("user belongs to no customer")
	// ErrNotPlatformAdmin is a User of a Customer asking to manage Customers.
	ErrNotPlatformAdmin = errors.New("only a platform admin manages customers")
	// ErrNotCustomerAdmin is a Viewer or a Platform Admin asking to manage the
	// Users of a Customer.
	ErrNotCustomerAdmin = errors.New("only a customer admin manages users")
	// ErrLastCustomerAdmin is a change that would leave a Customer without an
	// active Customer Admin.
	ErrLastCustomerAdmin = errors.New("a customer keeps at least one active customer admin")
	// ErrUserDisabled is a User disabled by a Customer Admin.
	ErrUserDisabled = errors.New("user is disabled")
	// ErrCustomerDeactivated is a Customer that is no longer served: its Users
	// cannot sign in and its CMDB Source does not sync.
	ErrCustomerDeactivated = errors.New("customer is deactivated")
)

// IDs are generated by the caller, so the domain stays free of randomness.
type CustomerID uuid.UUID

func (id CustomerID) String() string { return uuid.UUID(id).String() }

type Customer struct {
	id   CustomerID
	name string
}

// NewCustomer trims the name. Names are unique regardless of case, which only
// the database can check.
func NewCustomer(id CustomerID, name string) (Customer, error) {
	name = strings.TrimSpace(name)
	switch {
	case id == CustomerID{}:
		return Customer{}, fmt.Errorf("%w: zero id", ErrInvalidCustomer)
	case name == "":
		return Customer{}, fmt.Errorf("%w: empty name", ErrInvalidCustomer)
	}
	return Customer{id: id, name: name}, nil
}

func (c Customer) ID() CustomerID { return c.id }

func (c Customer) Name() string { return c.name }

type UserID uuid.UUID

func (id UserID) String() string { return uuid.UUID(id).String() }

type Role int

// Stored as catalog ids (ADR 0006): never renumber.
const (
	PlatformAdmin Role = 1
	CustomerAdmin Role = 2
	Viewer        Role = 3
)

func (r Role) valid() bool { return r >= PlatformAdmin && r <= Viewer }

var roleCodes = map[Role]string{
	PlatformAdmin: "platform_admin",
	CustomerAdmin: "customer_admin",
	Viewer:        "viewer",
}

// Code is the stable lowercase snake_case name clients use for the role.
func (r Role) Code() string { return roleCodes[r] }

// ParseRole is the inverse of Role.Code.
func ParseRole(code string) (Role, error) {
	for r, c := range roleCodes {
		if c == code {
			return r, nil
		}
	}
	return 0, fmt.Errorf("%w: role %q", ErrInvalidUser, code)
}

func (r Role) String() string {
	switch r {
	case PlatformAdmin:
		return "Platform Admin"
	case CustomerAdmin:
		return "Customer Admin"
	case Viewer:
		return "Viewer"
	default:
		return fmt.Sprintf("Role(%d)", int(r))
	}
}

type User struct {
	id       UserID
	email    string
	role     Role
	customer CustomerID

	disabled            bool
	customerDeactivated bool
}

// NewUser keeps the email in the canonical form of ADR 0003, trimmed and
// lowercased, and does not check its syntax: that belongs to the edge that
// receives it. A Platform Admin has no Customer and every other role has one;
// the zero CustomerID means none.
func NewUser(id UserID, email string, role Role, customer CustomerID) (User, error) {
	email = strings.ToLower(strings.TrimSpace(email))
	switch {
	case id == UserID{}:
		return User{}, fmt.Errorf("%w: zero id", ErrInvalidUser)
	case email == "":
		return User{}, fmt.Errorf("%w: empty email", ErrInvalidUser)
	case !role.valid():
		return User{}, fmt.Errorf("%w: role %d", ErrInvalidUser, int(role))
	case role == PlatformAdmin && customer != CustomerID{}:
		return User{}, fmt.Errorf("%w: a platform admin belongs to no customer", ErrInvalidUser)
	case role != PlatformAdmin && customer == CustomerID{}:
		return User{}, fmt.Errorf("%w: a %s belongs to a customer", ErrInvalidUser, role)
	}
	return User{id: id, email: email, role: role, customer: customer}, nil
}

// UserState is what can stop a stored User from signing in.
type UserState struct {
	Disabled            bool
	CustomerDeactivated bool
}

func RestoreUser(id UserID, email string, role Role, customer CustomerID, state UserState) (User, error) {
	u, err := NewUser(id, email, role, customer)
	if err != nil {
		return User{}, err
	}
	u.disabled = state.Disabled
	u.customerDeactivated = state.CustomerDeactivated
	return u, nil
}

func (u User) ID() UserID { return u.id }

func (u User) Email() string { return u.email }

func (u User) Role() Role { return u.role }

// SignIn fails with ErrUserDisabled before ErrCustomerDeactivated: a disabled
// User is told to sign in again whatever their Customer's state, and learns
// nothing about it.
func (u User) SignIn() error {
	switch {
	case u.disabled:
		return fmt.Errorf("user %s: %w", u.id, ErrUserDisabled)
	case u.customerDeactivated:
		return fmt.Errorf("user %s: %w", u.id, ErrCustomerDeactivated)
	}
	return nil
}

// ActsFor is the Customer whose data the User works on. It fails with
// ErrNoCustomer for a Platform Admin, who cannot see any Customer's data.
func (u User) ActsFor() (CustomerID, error) {
	if u.role == PlatformAdmin {
		return CustomerID{}, ErrNoCustomer
	}
	return u.customer, nil
}

// ManageCustomers fails with ErrNotPlatformAdmin for every User of a
// Customer: only a Platform Admin creates, renames, deactivates and
// reactivates Customers.
func (u User) ManageCustomers() error {
	if u.role != PlatformAdmin {
		return ErrNotPlatformAdmin
	}
	return nil
}

// ManageUsers returns the Customer whose Users u manages. It fails with
// ErrNotCustomerAdmin for anyone but a Customer Admin.
func (u User) ManageUsers() (CustomerID, error) {
	if u.role != CustomerAdmin {
		return CustomerID{}, ErrNotCustomerAdmin
	}
	return u.customer, nil
}

// WithRole is u with role r. A User of a Customer cannot become a Platform
// Admin.
func (u User) WithRole(r Role) (User, error) {
	if _, err := NewUser(u.id, u.email, r, u.customer); err != nil {
		return User{}, err
	}
	u.role = r
	return u, nil
}

// RequireActiveCustomerAdmin fails with ErrLastCustomerAdmin when a Customer
// has no active Customer Admin left.
func RequireActiveCustomerAdmin(activeAdmins int) error {
	if activeAdmins == 0 {
		return ErrLastCustomerAdmin
	}
	return nil
}
